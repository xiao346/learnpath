export function illustrationFor(course: string, chapter: string, index: number): Illustration | null {
  const atlas = courses[course]
  const tile = chapterPictures[chapter]?.[index]
  if (!atlas || tile === undefined) return null
  const picture = pictures[atlas][tile]
  if (!picture) return null
  const { x, y } = atlasEdges[atlas]
  const col = tile % 3
  const row = Math.floor(tile / 3)
  const frame = { x: x[col] + 2, y: y[row] + 2, width: x[col + 1] - x[col] - 4, height: y[row + 1] - y[row] - 4 }
  return { src: `/images/knowledge/${atlas}.png`, tile, alt: picture[0], caption: picture[1], frame }
}
